import { fixturePath } from './lib/fixture-path.mjs';
import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";
import { writeFileSync, rmSync } from "node:fs";
import { acquireVerificationLock } from './lib/verification-lock.mjs';
import { activeFixtureDatabaseBudget as fixtureDatabaseBudget, fixtureDatabaseResources } from './lib/fixture-database-budget.mjs';
// This runner cannot target a supplied URL or existing database. Only its own
// disposable, portless container is ever mutated. All work is sequential.
const root = fileURLToPath(new URL("../", import.meta.url));
const image = "public.ecr.aws/supabase/postgres:17.6.1.166";
const container = "cita-booking-test-" + randomBytes(6).toString("hex");
const fixtureRunId = process.env.CITA_FIXTURE_RUN_ID ?? randomBytes(16).toString('hex');
if (!/^[a-f0-9-]{32,36}$/.test(fixtureRunId)) throw new Error('Invalid disposable fixture run identifier.');
const keep = process.argv.slice(2).includes("--keep");
const realStorage = process.argv.slice(2).includes("--real-storage");
const prepareOnly = process.argv.slice(2).includes('--prepare-only');
if (prepareOnly && !keep) throw new Error('--prepare-only requires --keep and never counts as SQL verification.');
const storageContainer = container + "-storage";
const fixtureSecret =
  "cita-local-disposable-jwt-secret-with-more-than-32-characters";
let storageCreated = false;
if (
  process.argv
    .slice(2)
    .some((argument) => !["--keep", "--real-storage", '--prepare-only'].includes(argument))
)
  throw new Error(
    "Only --keep, --real-storage and --prepare-only are supported; remote database targets are forbidden.",
  );
function command(args, input) {
  const result = spawnSync("docker", args, {
    cwd: root,
    input,
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
  });
  if (result.error || result.status !== 0)
    throw new Error(
      result.error?.message ?? result.stderr.trim() ?? "Docker failed",
    );
  return result.stdout;
}
function sql(input) {
  return command(
    [
      "exec",
      "-i",
      container,
      "psql",
      "-X",
      "-U",
      "supabase_admin",
      "-d",
      "postgres",
      "-v",
      "ON_ERROR_STOP=1",
      "-q",
    ],
    input,
  );
}
function assertSqlSuite(file, output) {
  const plan = output.match(/^\s*1\.\.(\d+)\s*$/m);
  const assertions = [...output.matchAll(/^\s*ok \d+\b/gm)].length;
  if (/\bnot ok\b|Bail out!/.test(output) || !plan || Number(plan[1]) === 0 || assertions !== Number(plan[1]))
    throw new Error(file + ': pgTAP failed.\n' + output);
  console.log(file + '\n' + output.trim());
}
const platform = `
create schema if not exists realtime;
create table if not exists realtime.messages(id bigint generated by default as identity,topic text,extension text,payload jsonb);
alter table realtime.messages enable row level security;
create or replace function realtime.topic() returns text language sql stable as $$select current_setting('realtime.topic',true)$$;
grant usage on schema realtime to anon,authenticated,service_role;
grant select on realtime.messages to authenticated;
create schema if not exists storage;
create table if not exists storage.buckets(id text primary key,name text not null,public boolean default false,file_size_limit bigint,allowed_mime_types text[]);
create table if not exists storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text,owner uuid,owner_id text,metadata jsonb,created_at timestamptz default now(),updated_at timestamptz default now(),last_accessed_at timestamptz default now());
alter table storage.objects enable row level security;
create or replace function storage.foldername(name text) returns text[] language sql immutable as $$select (string_to_array(name,'/'))[1:array_length(string_to_array(name,'/'),1)-1]$$;
grant usage on schema storage to anon,authenticated,service_role;
grant all on storage.buckets,storage.objects to service_role;
create or replace function auth.uid() returns uuid language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),(nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub'))::uuid$$;
create or replace function auth.role() returns text language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),(nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'role'))$$;
create or replace function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),'')::jsonb,'{}'::jsonb)$$;
alter function auth.uid() owner to supabase_auth_admin;
alter function auth.role() owner to supabase_auth_admin;
alter function auth.jwt() owner to supabase_auth_admin;
`;
let created = false;
let localNetwork = null;
const verificationLease = acquireVerificationLock(root);
try {
  command(["image", "inspect", image]); // Never pull a large image implicitly.
  if (keep || realStorage) {
    localNetwork = container + "-net";
    command(["network", "create", "--internal", '--label', 'com.cita-suite.fixture-run=' + fixtureRunId, localNetwork]);
  }
  command([
    "run",
    "-d",
    "--name",
    container,
    "--label",
    "com.cita-suite.booking-fixture=true",
    '--label', 'com.cita-suite.fixture-run=' + fixtureRunId,
    "--network",
    localNetwork ?? "none",
    "--memory",
    fixtureDatabaseResources.memory,
    "--cpus",
    fixtureDatabaseResources.cpus,
    "-e",
    "POSTGRES_PASSWORD=cita-disposable-test-only",
    image,
    "postgres",
    ...fixtureDatabaseResources.settings.flatMap((setting) => ["-c", setting]),
    "-c",
    `max_connections=${fixtureDatabaseBudget.maximum}`,
    "-c",
    `superuser_reserved_connections=${fixtureDatabaseBudget.superuserReserved}`,
    "-c",
    "listen_addresses=*",
    "-c",
    "cron.database_name=postgres",
  ]);
  created = true;
  let ready = false;
  for (let attempt = 0; attempt < 100; attempt++) {
    // The image's temporary initialization server accepts Unix sockets before
    // platform migrations finish. TCP readiness waits for the final server.
    const result = spawnSync(
      "docker",
      [
        "exec",
        container,
        "pg_isready",
        "-h",
        "127.0.0.1",
        "-U",
        "supabase_admin",
      ],
      { encoding: "utf8" },
    );
    if (result.status === 0) {
      ready = true;
      break;
    }
    await new Promise((resolve) => setTimeout(resolve, 500));
  }
  if (!ready)
    throw new Error(
      "Disposable PostgreSQL did not start.\n" +
        command(["logs", "--tail", "30", container]),
    );
  sql(
    realStorage
      ? platform.slice(
          0,
          platform.indexOf("create schema if not exists storage;"),
        ) +
          platform.slice(
            platform.indexOf("create or replace function auth.uid()"),
          )
      : platform,
  );
  sql("alter role supabase_admin password 'cita-disposable-test-only';");
  // The hosted platform's PostgREST login role: its sessions reject an UPDATE or
  // DELETE without WHERE, also inside the functions a request calls.
  sql("alter role authenticator password 'cita-disposable-test-only'; alter role authenticator set session_preload_libraries = 'safeupdate';");
  // Supabase gives the API roles no automatic grant on new public objects (projects
  // created since 30 May 2026, existing ones from 30 October). The migrations run here
  // as supabase_admin and in hosted projects as postgres: with neither role granting
  // by default, every privilege a table needs comes from its migration, as in a
  // project rebuilt from them.
  sql(["supabase_admin", "postgres"].flatMap((owner) => ["tables", "sequences", "functions"].map((kind) =>
    `alter default privileges for role ${owner} in schema public revoke all on ${kind} from anon, authenticated, service_role;`)).join("\n"));
  if (realStorage) {
    const storageImage = "public.ecr.aws/supabase/storage-api:v1.70.3";
    command(["image", "inspect", storageImage]);
    command([
      "run",
      "-d",
      "--name",
      storageContainer,
      "--label",
      "com.cita-suite.booking-fixture=true",
      '--label', 'com.cita-suite.fixture-run=' + fixtureRunId,
      "--network",
      localNetwork,
      "--memory",
      "192m",
      "--cpus",
      "0.5",
      "-e",
      "NODE_OPTIONS=--max-old-space-size=96",
      "-e",
      "SERVER_HOST=0.0.0.0",
      "-e",
      "SERVER_PORT=5000",
      "-e",
      "AUTH_JWT_SECRET=" + fixtureSecret,
      "-e",
      "AUTH_JWT_ALGORITHM=HS256",
      "-e",
      "DATABASE_URL=postgres://supabase_admin:cita-disposable-test-only@" +
        container +
        ":5432/postgres",
      "-e",
      `DATABASE_MAX_CONNECTIONS=${fixtureDatabaseBudget.storage}`,
      "-e",
      "DB_SUPER_USER=supabase_admin",
      "-e",
      "DB_INSTALL_ROLES=false",
      "-e",
      "STORAGE_BACKEND=file",
      "-e",
      "STORAGE_FILE_BACKEND_PATH=/tmp/cita-fixture-storage",
      "-e",
      "TENANT_ID=cita-isolated",
      "-e",
      "STORAGE_S3_BUCKET=cita-isolated",
      "-e",
      "REGION=local",
      "-e",
      "UPLOAD_FILE_SIZE_LIMIT=5000000",
      "-e",
      "UPLOAD_FILE_SIZE_LIMIT_STANDARD=5000000",
      "-e",
      "IMAGE_TRANSFORMATION_ENABLED=false",
      "-e",
      "PG_QUEUE_ENABLE=false",
      "-e",
      "OTEL_METRICS_ENABLED=false",
      storageImage,
    ]);
    storageCreated = true;
    const storageAddress = command([
      "inspect",
      "--format",
      "{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}",
      storageContainer,
    ]).trim();
    const storageOrigin = "http://" + storageAddress + ":5000";
    let healthy = false;
    for (let n = 0; n < 100; n++) {
      try {
        const response = await fetch(storageOrigin + "/status", {
          signal: AbortSignal.timeout(1000),
        });
        if (response.ok) {
          healthy = true;
          break;
        }
      } catch {}
      await new Promise((resolve) => setTimeout(resolve, 500));
    }
    if (!healthy)
      throw new Error(
        "Isolated Storage API did not become ready.\n" +
          command(["logs", "--tail", "12", storageContainer]),
      );
    writeFileSync(
      fixturePath("storage.json"),
      JSON.stringify({
        database: container,
        container: storageContainer,
        origin: storageOrigin,
        version: "v1.70.3",
        fileBackend: true,
      }),
      { mode: 0o600 },
    );
  }
  const migrations = readdirSync(root + "supabase/migrations")
    .filter((file) => file.endsWith(".sql"))
    .sort();
  const upgradeDirectory = root + 'supabase/tests/migrations/';
  const upgradeFiles = existsSync(upgradeDirectory) ? readdirSync(upgradeDirectory).sort() : [];
  for (const path of upgradeFiles) {
    const match = path.match(/^(.*\.sql)\.(before|after)\.sql$/);
    if (!match || !migrations.includes(match[1]) ||
      !upgradeFiles.includes(match[1] + '.before.sql') || !upgradeFiles.includes(match[1] + '.after.sql'))
      throw new Error('Unpaired or unrecognized migration upgrade fixture: ' + path);
  }
  for (const file of migrations) {
    try {
      const upgrade = upgradeFiles.includes(file + '.before.sql');
      if (upgrade && !prepareOnly) sql(readFileSync(upgradeDirectory + file + '.before.sql', 'utf8'));
      sql(readFileSync(root + "supabase/migrations/" + file, "utf8"));
      if (upgrade && !prepareOnly) assertSqlSuite('migration-upgrade/' + file,
        sql(readFileSync(upgradeDirectory + file + '.after.sql', 'utf8')));
    } catch (error) {
      throw new Error(file + ": " + error.message);
    }
  }
  console.log(
    "Clean reconstruction: " + migrations.length + " migrations applied.",
  );
  // Preserve the effective schema even when a newly added negative contract
  // exposes a bug and stops the suite. This provisional receipt is never SQL
  // approval; the manager requires sqlVerified=true before browser execution.
  writeFileSync(fixturePath('database.json'), JSON.stringify({ container, network: localNetwork, runId: fixtureRunId, sqlVerified: false }), { mode: 0o600 });
  const catalog = spawnSync(process.execPath, ['scripts/catalog-disposable-database.mjs'], { cwd: root, env: process.env, stdio: 'inherit' });
  if (catalog.status !== 0 || catalog.error) throw new Error('Could not retain the reconstructed database catalog.');
  if (!prepareOnly) {
  const sqlTests = readdirSync(root + 'supabase/tests').filter(file => file.endsWith('.sql')).sort();
  if (!sqlTests.length || sqlTests[0] !== '000_pgtap_setup.sql')
    throw new Error('SQL suite discovery is empty or pgTAP setup is missing.');
  for (const file of sqlTests) {
    // Pass the same immutable vectors used by TypeScript to this psql session.
    // Only fixture data is quoted here; no environment or remote SQL target.
    const context = file === 'price_contract_parity.sql'
      ? "select set_config('cita.test_price_vectors','" +
        JSON.stringify(JSON.parse(readFileSync(root + 'packages/shared/src/price-contract-vectors.json', 'utf8'))).replaceAll("'", "''") + "',false) is not null;\n"
      : '';
    const output = sql(context + readFileSync(root + "supabase/tests/" + file, "utf8"));
    assertSqlSuite(file, output);
  }
  const concurrencyTests = readdirSync(root + 'supabase/tests').filter(file => /^run_.*_concurrency\.sh$/.test(file)).sort();
  if (!concurrencyTests.length) throw new Error('No concurrency SQL suites discovered.');
  for (const file of concurrencyTests) {
    const output = command([
      'exec', '-i', '-e',
      'SUPABASE_TEST_DB_URL=postgresql://supabase_admin:cita-disposable-test-only@127.0.0.1:5432/postgres',
      container, 'bash', '-s'
    ], readFileSync(root + 'supabase/tests/' + file, 'utf8'));
    console.log(file + '\n' + output.trim());
  }
  }
  if(keep)sql("select cron.unschedule(jobid) from cron.job;");
  if (keep) writeFileSync(fixturePath('database.json'), JSON.stringify({ container, network: localNetwork, runId: fixtureRunId, sqlVerified: !prepareOnly }), { mode: 0o600 });
  console.log(
    (prepareOnly ? 'PREPARED ONLY: SQL suites and concurrency were not executed. ' : "PASS: isolated SQL contracts. ") +
      (realStorage
        ? "Storage API schema is real; file transfer still needs HTTP verification."
        : "Storage/Realtime services and network delivery are not exercised by this runner."),
  );
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
} finally {
  if (created && keep && !process.exitCode)
    console.log(
      "Disposable database retained for local development only: " +
        container +
        (storageCreated?"\nStorage cleanup: docker rm -f -v "+storageContainer:"") +
        "\nCleanup: docker rm -f -v " +
        container +
        "\nNetwork cleanup: docker network rm " +
        localNetwork,
    );
  else {
    if (storageCreated) command(["rm", "-f", "-v", storageContainer]);
    if (realStorage) rmSync(fixturePath("storage.json"), { force: true });
    if (created) command(["rm", "-f", "-v", container]);
    if (localNetwork) command(["network", "rm", localNetwork]);
    rmSync(fixturePath('database.json'), { force: true });
  }
  verificationLease.release();
}
